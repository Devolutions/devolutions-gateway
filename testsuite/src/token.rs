/// Returns the provisioner private key, whose public key [`provisioner_public_key_data`] returns.
pub fn provisioner_key() -> PrivateKey {
    PrivateKey::from_pem_str(PROVISIONER_KEY).expect("parse the provisioner key")
}

/// Returns a private key the Gateway doesn't trust.
pub fn untrusted_key() -> PrivateKey {
    PrivateKey::from_pem_str(UNTRUSTED_KEY).expect("parse the untrusted key")
}

/// Returns the provisioner public key, encoded for [`crate::dgw_config::DgwConfig`].
pub fn provisioner_public_key_data() -> String {
    let der = provisioner_key()
        .to_public_key()
        .and_then(|public_key| public_key.to_der())
        .expect("encode the provisioner public key");

    // The `m` multibase prefix stands for base64 without padding.
    format!("m{}", base64::engine::general_purpose::STANDARD_NO_PAD.encode(der))
}

/// Signs a token with the given content type (`cty` header) and key ID (`kid` header).
pub fn sign_token(key: &PrivateKey, content_type: &str, kid: Option<&str>, claims: &serde_json::Value) -> String {
    let mut jwt = CheckedJwtSig::new_with_cty(JwsAlg::RS256, content_type, claims);
    jwt.header.kid = kid.map(str::to_owned);
    jwt.encode(key).expect("sign the token")
}
